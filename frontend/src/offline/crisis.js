export const CRISIS_REPLY = `检测到你可能正处于非常艰难的时刻。你不是一个人，请一定优先照顾自己的安全。

建议你：
1. 立即联系你信任的家人或朋友，告诉他们你此刻的感受；
2. 拨打心理援助热线（全国 12356）寻求专业支持；
3. 若情况紧急，请立即拨打 120 或 110。

生命值得被认真对待，请给自己一次被帮助的机会。❤️`

export function containsCrisis(content) {
  if (!content) return false
  return CRISIS_KEYWORDS.some((kw) => content.includes(kw))
}
